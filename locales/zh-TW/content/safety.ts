export const SAFETY_SCENARIOS: SafetyScenario[] = original.map((scenario, index) => {
  const [title, situation, principle, choices] = translations[index]!;
  return {
    ...scenario,
    title,
    situation,
    principle,
    question: '你會怎麼做？',
    choices: scenario.choices.map((choice, i) => ({
      ...choice,
      label: choices[i]![0],
      feedback: choices[i]![1],
    })),
  };
});
export const SAFETY_LAB_IDS = SAFETY_SCENARIOS.map((scenario) => `safety:${scenario.id}`);
